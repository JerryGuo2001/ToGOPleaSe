"""Derive/verify the r119 schema against all 250 original binary objects.
Run node tools/inspect-story.js first, then this script. No game commands sent.
"""
import json, importlib.util, sys
from pathlib import Path
spec=importlib.util.spec_from_file_location('zil','tools/zil-reader.py'); z=importlib.util.module_from_spec(spec); spec.loader.exec_module(z)
s=z.source_objects(); objects=json.loads(Path('tools/story-inspection.json').read_text()); o={x['id']:x for x in objects}
directions=dict(zip(['NORTH','EAST','WEST','SOUTH','NE','NW','SE','SW','UP','DOWN','IN','OUT','LAND'],range(31,18,-1)))
candidates={k:set(x['id'] for x in objects if x['name']==v['props'].get('DESC',[''])[0].strip('"')) for k,v in s.items()}
candidates.update({'GLOBAL-OBJECTS':{61},'LOCAL-GLOBALS':{48},'ROOMS':{39}})
# Identity constraints: names, direct children, exits, room local-global lists.
edges=[]
for k,v in s.items():
 p=v['props']
 if k!='ADVENTURER' and p.get('IN',[''])[0] in s:
  edges.append((k,p['IN'][0],lambda x:o[x]['parent']))
 for d,prop in directions.items():
  e=p.get(d,[])
  if v['kind']=='ROOM' and len(e)>1 and e[0]=='TO' and e[1] in s:
   edges.append((k,e[1],lambda x,n=str(prop):o[x]['props'].get(n,[None])[0]))
while True:
 before=repr(candidates)
 for a,b,f in edges:
  candidates[a]={x for x in candidates[a] if f(x) in candidates[b]}
  candidates[b]={y for y in candidates[b] if any(f(x)==y for x in candidates[a])}
 singles=set(next(iter(v)) for v in candidates.values() if len(v)==1)
 for k,v in candidates.items():
  if len(v)>1:candidates[k]=v-singles
 if repr(candidates)==before:break
assert all(len(v)==1 for v in candidates.values()),{k:v for k,v in candidates.items() if len(v)!=1}
mapping={k:next(iter(v)) for k,v in candidates.items()}
# Infer attributes by comparing flag membership across the complete source.
flags=sorted(set(f for v in s.values() for f in v['props'].get('FLAGS',[])))
flagmap={}
for flag in flags:
 symbols=[k for k in s if k not in ['WEST-OF-HOUSE','ADVENTURER']]
 matches=[bit for bit in range(32) if all((flag in s[k]['props'].get('FLAGS',[])) == (bit in o[mapping[k]]['attrs']) for k in symbols)]
 if len(matches)==1: flagmap[flag]=matches[0]
 else: print('Not used by policy; unresolved attribute:',flag,matches)
# Generate noun phrases from source synonyms/adjectives. Only registered parser words.
registry=[]
for k,v in s.items():
 p=v['props']; desc=p.get('DESC',['""'])[0].strip('"')
 syn=[x.lower() for x in p.get('SYNONYM',[]) if isinstance(x,str)]
 adj=[x.lower() for x in p.get('ADJECTIVE',[]) if isinstance(x,str)]
 words=desc.lower().replace('-',' ').split()
 nouns=[w for w in words if any(w[:6]==x[:6] for x in syn)]
 noun=nouns[-1] if nouns else (syn[0] if syn else '')
 adjectives=[w for w in words if any(w[:6]==x[:6] for x in adj) and w!=noun]
 phrase=' '.join(adjectives[:1]+[noun])
 registry.append({'id':mapping[k],'symbol':k,'kind':v['kind'].lower(),'name':desc,'noun':phrase,'synonyms':syn,'adjectives':adj})
registry.sort(key=lambda x:x['id'])
result={'gameVersion':'119/880429','sha256':'37084966477dff679282de42974b2077156b1bd68fad92a65d4ea94d8eb64d79','globals':{'HERE':0,'SCORE':1,'MOVES':2,'LIT':51},'objects':registry,'attributes':flagmap,'directions':directions,'properties':{'GLOBAL':5,'TEXT':8,'CAPACITY':10,'LDESC':11,'TVALUE':12,'VALUE':13,'FDESC':14,'SIZE':15,'ADJECTIVE':16,'ACTION':17,'SYNONYM':18}}
generated='// Generated by tools/map-story.py; pinned r119 identity metadata, not game logic.\nexport const SCHEMA = '+json.dumps(result,indent=2)+';\n'
if '--check' in sys.argv:
 assert Path('js/story-schema.js').read_text()==generated, 'Committed schema differs from story/source derivation'
else:
 Path('js/story-schema.js').write_text(generated)
print('Verified 250 object identities and uniquely identifiable attribute numbers against matching source and binary.')
print(flagmap)
